/* =========================
   LANGUAGE FUNCTIONS
========================= */

function getRivoLanguage() {

    return localStorage.getItem("rivoLanguage") || "en";

}


function rivoText(key) {

    return RIVO_TRANSLATIONS[getRivoLanguage()][key] ?? key;

}


function setRivoLanguage(language) {

    if (!RIVO_TRANSLATIONS[language]) {

        language = "en";

    }

    localStorage.setItem("rivoLanguage", language);

    document.documentElement.lang = language;

    document.documentElement.dir =
        language === "ar" ? "rtl" : "ltr";


    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.dataset.i18n;

        const translatedText = RIVO_TRANSLATIONS[language][key];

        if (translatedText !== undefined) {

            element.textContent = translatedText;

        }

    });


    document.querySelectorAll("[data-language]").forEach(button => {

        button.classList.toggle(
            "active",
            button.dataset.language === language
        );

    });


    window.dispatchEvent(
        new CustomEvent("rivo-language-change")
    );

}


/* =========================
   LANGUAGE BUTTONS
========================= */

document.querySelectorAll("[data-language]").forEach(button => {

    button.addEventListener("click", () => {

        setRivoLanguage(button.dataset.language);

    });

});


