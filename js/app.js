/* =========================
   DISPLAY PRODUCTS
========================= */

const productsContainer =
    document.getElementById("productsContainer");


function displayProducts() {

    if (!productsContainer) {

        return;

    }

    const language = getRivoLanguage();

    const translations = RIVO_TRANSLATIONS[language];


    productsContainer.innerHTML = RIVO_PRODUCTS.map(product => {

        return `

            <article class="product-card">

                <a
                    class="product-card-image"
                    href="product.html?id=${encodeURIComponent(product.id)}"
                >

                    <img
                        src="${product.image}"
                        alt="${product.name}"
                        loading="lazy"
                    >

                    <span class="product-badge">

                        ${product.badge}

                    </span>

                    <span class="product-arrow">

                        ↗

                    </span>

                </a>


                <div class="product-card-info">

                    <div>

                        <a
                            class="product-name"
                            href="product.html?id=${encodeURIComponent(product.id)}"
                        >

                            ${product.name}

                        </a>

                        <p class="product-subtitle">

                            ${product.subtitle}

                        </p>

                    </div>


                    <strong class="product-price">

                        ${Number(product.price).toLocaleString()}
                        ${RIVO_CONFIG.currency}

                    </strong>

                </div>


                <a
                    class="text-link"
                    href="product.html?id=${encodeURIComponent(product.id)}"
                >

                    ${translations.viewProduct}

                </a>

            </article>

        `;

    }).join("");


    const countElement = document.getElementById("productCount");

    if (countElement) {

        countElement.textContent =
            `${String(RIVO_PRODUCTS.length).padStart(2, "0")} ${translations.products}`;

    }

}


/* =========================
   START WEBSITE
========================= */

window.addEventListener("rivo-language-change", displayProducts);

setRivoLanguage(getRivoLanguage());

displayProducts();